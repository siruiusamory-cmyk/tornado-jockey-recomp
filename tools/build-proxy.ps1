
$ErrorActionPreference = 'Stop'
Set-Location (Split-Path $PSScriptRoot -Parent)
$root = (Get-Location).Path

$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
if (-not (Test-Path $vswhere)) { throw "vswhere.exe not found: $vswhere" }
$vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vs) { throw 'no Visual Studio install with the x86 C++ tools' }
$vcvars = Join-Path $vs 'VC\Auxiliary\Build\vcvars32.bat'

$out = Join-Path $root 'build\proxy'
New-Item -ItemType Directory -Force $out | Out-Null

$dxc = Get-ChildItem "${env:ProgramFiles(x86)}\Windows Kits\10\bin\*\x64\dxc.exe" -ErrorAction SilentlyContinue |
    Sort-Object FullName -Descending | Select-Object -First 1 -ExpandProperty FullName
if (-not $dxc) { throw 'dxc.exe not found in the Windows SDK bin' }
$shaders = Join-Path $out 'shaders'
New-Item -ItemType Directory -Force $shaders | Out-Null
$hlsl = Join-Path $root 'port\proxy\render\shaders\tj.hlsl'
foreach ($entry in @(@('vs_6_0', 'VSMain', 'vs.cso'), @('ps_6_0', 'PSMain', 'ps.cso'))) {
    & $dxc -T $entry[0] -E $entry[1] -Fo (Join-Path $shaders $entry[2]) $hlsl
    if ($LASTEXITCODE) { throw "dxc failed for $($entry[1])" }
}
$embed = @'
import sys
lines = ['// Generated by tools/build-proxy.ps1 from port/proxy/render/shaders/tj.hlsl.']
for name, path in (('kShaderVS', sys.argv[1]), ('kShaderPS', sys.argv[2])):
    data = open(path, 'rb').read()
    lines.append('static const unsigned char %s[] = {%s};' % (name, ','.join(str(b) for b in data)))
    lines.append('static const unsigned %sSize = %d;' % (name, len(data)))
print('\n'.join(lines))
'@
$embed | python -B - (Join-Path $shaders 'vs.cso') (Join-Path $shaders 'ps.cso') |
    Set-Content -Encoding ascii (Join-Path $out 'd3d12_shaders.h')
if (-not (Test-Path (Join-Path $out 'd3d12_shaders.h'))) { throw 'shader header generation failed' }

$generator = @'
import sys
sys.path.insert(0, 'tools')
import d3d8_census as c
import re
if c.sha256(c.HEADER) != c.HEADER_SHA256:
    raise SystemExit('tools/vtable/d3d8.h does not match its pin')
text = c.HEADER.read_text(encoding='latin1')
interfaces = ('IDirect3D8', 'IDirect3DDevice8', 'IDirect3DTexture8', 'IDirect3DSurface8',
              'IDirect3DVertexBuffer8', 'IDirect3DIndexBuffer8', 'IDirect3DCubeTexture8')
methods = {}
for interface in interfaces:
    start = text.index(f'DECLARE_INTERFACE_({interface},')
    end = text.index('\n};', start)
    methods[interface] = re.findall(
        r'STDMETHOD_?\((?:[^,()]+,)?\s*([A-Za-z_]\w*)\s*\)\s*\(', text[start:end])
width = max(len(m) for m in methods.values())
lines = ['static const char* const SLOT_NAMES[%d][%d] = {' % (len(interfaces), width)]
for interface in interfaces:
    names = methods[interface] + ['?'] * (width - len(methods[interface]))
    lines.append('    {' + ', '.join('"%s"' % m for m in names) + '},')
lines.append('};')
lines.append('static const unsigned SLOT_COUNTS[%d] = {%s};' % (
    len(interfaces), ', '.join(str(len(methods[i])) for i in interfaces)))
print('\n'.join(lines))
'@
$slots = $generator | python -B -
if ($LASTEXITCODE -or -not $slots) { throw 'slot-name generation failed' }
$slots | Set-Content -Encoding ascii (Join-Path $out 'd3d8_slots.h')

$bat = Join-Path $out 'build.bat'
@"
@echo off
call "$vcvars" >nul
cl 2>&1 | findstr /i "Optimizing Compiler"
cl /nologo /LD /O2 /MT /EHsc /W4 /arch:IA32 /D_CRT_SECURE_NO_WARNINGS /I"$out" "$root\port\proxy\d3d8_proxy.cpp" /Fo:"$out\d3d8_proxy.obj" /link /DEF:"$root\port\proxy\d3d8_proxy.def" /IMPLIB:"$out\d3d8_proxy.lib" /OUT:"$out\d3d8.dll" /MAP:"$out\d3d8.map" user32.lib gdi32.lib d3d12.lib dxgi.lib dxguid.lib
if errorlevel 1 exit /b 1
dumpbin /nologo /headers "$out\d3d8.dll"
dumpbin /nologo /exports "$out\d3d8.dll"
"@ | Set-Content -Encoding ascii $bat

$log = Join-Path $env:TEMP 'tj-build-proxy.txt'
$build = Start-Process cmd.exe -ArgumentList '/c', $bat -WorkingDirectory $root -NoNewWindow -PassThru -RedirectStandardOutput $log
$build.PriorityClass = 'BelowNormal'
$build.WaitForExit()
Get-Content $log
if ($build.ExitCode) { throw "build failed (exit $($build.ExitCode))" }
